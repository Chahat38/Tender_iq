-- ===========================================================================
-- row level security
-- ===========================================================================

-- Shared source data: anyone signed in may read, nobody may write from
-- the browser (the collector and Edge Functions use the service role,
-- which bypasses RLS).
do $$
declare t text;
begin
    foreach t in array array[
        'procurement_sources', 'opportunities', 'opportunity_documents',
        'opportunity_requirements', 'opportunity_updates', 'opportunity_ai'
    ] loop
        execute format('alter table %I enable row level security', t);
        execute format(
            'create policy "%s_select_authenticated" on %I for select to authenticated using (true)',
            t, t
        );
    end loop;
end $$;

-- Operational tables: RLS on, no policy at all -> only the service role
-- (which bypasses RLS) can touch them.
do $$
declare t text;
begin
    foreach t in array array[
        'source_fetch_logs', 'analysis_runs', 'dedup_review_queue',
        'operational_alerts', 'audit_log'
    ] loop
        execute format('alter table %I enable row level security', t);
    end loop;
end $$;

-- User tables: every policy is scoped to the row owner. Where the UI
-- owns the row (profiles, preferences, saves, alerts, RFP drafts) the
-- owner may insert/update/delete; where the backend owns the row
-- (AI matches, usage counters, subscriptions) clients may only read
-- their own rows.
do $$
declare t text;
begin
    foreach t in array array[
        'profiles', 'company_capabilities', 'target_regions',
        'target_categories', 'opportunity_matches', 'saved_opportunities',
        'alerts', 'rfps', 'rfp_sections', 'subscriptions', 'usage_counters'
    ] loop
        execute format('alter table %I enable row level security', t);
        execute format(
            'create policy "%s_select_own" on %I for select to authenticated using (auth.uid() = user_id)',
            t, t
        );
    end loop;
end $$;

do $$
declare t text;
begin
    foreach t in array array[
        'profiles', 'company_capabilities', 'target_regions',
        'target_categories', 'saved_opportunities', 'alerts',
        'rfps', 'rfp_sections'
    ] loop
        execute format(
            'create policy "%s_insert_own" on %I for insert to authenticated with check (auth.uid() = user_id)',
            t, t
        );
        execute format(
            'create policy "%s_update_own" on %I for update to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id)',
            t, t
        );
        execute format(
            'create policy "%s_delete_own" on %I for delete to authenticated using (auth.uid() = user_id)',
            t, t
        );
    end loop;
end $$;

