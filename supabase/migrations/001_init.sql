create table if not exists analysis_runs (
    id bigint generated by default as identity primary key,
    task text not null,
    provider text,
    model text,
    prompt_version text,
    duration_ms integer,
    tokens integer,
    status text not null,
    error_message text,
    user_id uuid,
    opportunity_id bigint references opportunities (id) on delete set null,
