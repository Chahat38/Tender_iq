-- TenderScout AI - initial Supabase/Postgres schema.
--
-- Target: Supabase (Postgres 15+). Applied by `supabase db push` or by
-- scripts/migrate_sqlite_to_postgres.py (which applies this file before
-- copying rows). Table and column names are a FIXED data contract with
-- the frontend - never rename them.
--
-- Layout rules (see DECISIONS.md):
--   * shared tables   ... source data, SELECT for authenticated, no
--                         client writes at all (only the collector /
--                         service role writes),
--   * user tables     ... one owner (user_id) per row, RLS
--                         `auth.uid() = user_id`; AI/ops-owned rows
--                         (matches, usage, subscriptions) are
--                         SELECT-own only - the backend writes them,
--   * operational     ... telemetry and queues, service-role only
--                         (RLS enabled with no policy = deny all).
--
-- Notes:
--   * `gen_random_uuid()` is built into Postgres 13+ (no pgcrypto).
--   * `auth.uid()` is the Supabase JWT claim helper. For tests against
--     a plain Postgres, scripts/apply_migration.py installs a minimal
--     `auth` shim first (see collector/tests/test_rls_postgres.py).

create extension if not exists pg_trgm;

-- ===========================================================================
-- shared: procurement sources
-- ===========================================================================
create table if not exists procurement_sources (
    id bigint generated by default as identity primary key,
    name text not null unique,
    adapter_type text not null,
    base_url text,
    active boolean not null default true,
    robots_allowed boolean,
    terms_checked boolean not null default false,
    requires_authentication boolean not null default false,
    crawl_frequency text,
    last_crawled_at timestamptz,
    last_status text,
    consecutive_failures integer not null default 0,
    created_at timestamptz not null default now()
);

-- ===========================================================================
-- shared: opportunities (the core contract - names are frozen)
-- ===========================================================================
create table if not exists opportunities (
    id bigint generated by default as identity primary key,
    source_id bigint not null references procurement_sources (id),
    external_id text not null,
    reference_number text,
    title text,
    organization text,
    description text,
    source_url text not null,
    source_name text,
    published_at timestamptz,
    deadline timestamptz,
    location text,
    province text,
    category text,
    procurement_type text,
    content_hash text not null,
    is_primary boolean not null default true,
    duplicate_group_id text,
    first_seen_at timestamptz not null default now(),
    last_seen_at timestamptz not null default now(),
    last_verified_at timestamptz not null default now(),
    source_count integer not null default 1,
    raw_content text,
    unique (source_id, external_id)
);

-- Upsert fallback key: when a source republishes a notice under a new
-- external_id, (source_id, reference_number) finds the existing row.
-- Deliberately NOT unique: sources legitimately reuse a reference across
-- notices, and a uniqueness violation would break collection.
create index if not exists idx_opportunities_source_ref
    on opportunities (source_id, reference_number);

create index if not exists idx_opportunities_deadline
    on opportunities (deadline);
create index if not exists idx_opportunities_published_at
    on opportunities (published_at);
create index if not exists idx_opportunities_category_province
    on opportunities (category, province);
create index if not exists idx_opportunities_duplicate_group
    on opportunities (duplicate_group_id);
create index if not exists idx_opportunities_source
    on opportunities (source_id);

-- Full-text search (spec: GIN over title || organization || description
-- || reference_number).
create index if not exists idx_opportunities_fts
    on opportunities
    using gin (to_tsvector(
        'english',
        coalesce(title, '') || ' ' || coalesce(organization, '') || ' ' ||
        coalesce(description, '') || ' ' || coalesce(reference_number, '')
    ));

-- Trigram index for fuzzy duplicate scoring (spec: pg_trgm on title).
create index if not exists idx_opportunities_title_trgm
    on opportunities using gin (title gin_trgm_ops);

