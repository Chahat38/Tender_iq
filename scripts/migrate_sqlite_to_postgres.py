#!/usr/bin/env python3
"""Copy an existing TenderScout SQLite database into Postgres/Supabase.

Usage (from the repository root):

    export DATABASE_URL="postgresql://user:pass@host:5432/dbname"
    python scripts/migrate_sqlite_to_postgres.py --sqlite collector/tenderscout.db

Behaviour:

* applies ``supabase/migrations/001_init.sql`` first (unless
  ``--skip-schema``), installing ``scripts/pg_auth_shim.sql`` when the
  target is a plain Postgres without Supabase's ``auth`` schema,
* copies every collector table, preserving ids (the schema uses
  ``generated by default as identity`` for exactly this reason),
* is idempotent: re-running skips rows that already exist (``ON CONFLICT
  DO NOTHING``), so an interrupted migration can simply be repeated,
* refuses to run without ``DATABASE_URL`` and prints a per-table
  inserted/skipped summary.

User-owned tables (profiles, matches, saved, alerts, rfps, ...) are only
copied with ``--user-tables``: their ``user_id`` values must be real
auth UUIDs, and collector-only databases do not contain them.
"""

