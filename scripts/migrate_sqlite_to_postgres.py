def sqlite_tables(conn: Any) -> set[str]:
    """Names of the tables that exist in the SQLite database."""
    rows = conn.execute(
        "SELECT name FROM sqlite_master WHERE type = 'table'"
    ).fetchall()
    return {row["name"] for row in rows}


def convert_value(column: str, value: Any) -> Any:
    """Convert one SQLite value to its Postgres form."""
    if value is None:
        return None
    if column in BOOLEAN_COLUMNS:
        return bool(value)
    return value


def read_rows(
    conn: Any, table: str, columns: list[str]
) -> tuple[list[tuple[Any, ...]], list[str]]:
    """Read ``columns`` from a SQLite table.

    Returns ``(rows, usable_columns)``; empty when the table (or every
    requested column) is absent from this database.
    """
    existing = sqlite_tables(conn)
    if table not in existing:
        return [], []
    present = {
        row["name"] for row in conn.execute(f"PRAGMA table_info({table})")
    }
    usable = [c for c in columns if c in present]
    if not usable:
        return [], []
    rows = conn.execute(
        f"SELECT {', '.join(usable)} FROM {table}"
    ).fetchall()
    return [tuple(convert_value(c, row[c]) for c in usable) for row in rows], usable


def insert_rows(
    conn: Any, table: str, columns: list[str], rows: list[tuple[Any, ...]]
) -> tuple[int, int]:
    """Insert rows with ON CONFLICT DO NOTHING; return (inserted, skipped)."""
    if not rows:
        return 0, 0
    placeholders = ", ".join(["%s"] * len(columns))
    sql = (
        f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({placeholders}) "
        "ON CONFLICT DO NOTHING"
    )
    before = _count(conn, table)
    with conn.cursor() as cur:
        cur.executemany(sql, rows)
    conn.commit()
    after = _count(conn, table)
    return after - before, len(rows) - (after - before)


def _count(conn: Any, table: str) -> int:
    with conn.cursor() as cur:
        cur.execute(f"SELECT COUNT(*) AS n FROM {table}")
        return int(cur.fetchone()["n"])


def apply_schema(conn: Any, verbose: bool = True) -> None:
    """Apply the auth shim (when needed) and 001_init.sql."""
    with conn.cursor() as cur:
        cur.execute("select to_regclass('auth.users') is null as missing")
        missing_auth = bool(cur.fetchone()["missing"])
    if missing_auth:
        if verbose:
            print("auth schema not found -> installing scripts/pg_auth_shim.sql")
        with conn.cursor() as cur:
            cur.execute(AUTH_SHIM_SQL.read_text(encoding="utf-8"))
        conn.commit()
    with conn.cursor() as cur:
        cur.execute(MIGRATION_SQL.read_text(encoding="utf-8"))
    conn.commit()
    if verbose:
        print(f"applied {MIGRATION_SQL.relative_to(REPO_ROOT)}")


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Copy a TenderScout SQLite database into Postgres"
    )
    parser.add_argument(
        "--sqlite",
        default=os.environ.get("TENDERSCOUT_DB_PATH", "collector/tenderscout.db"),
        help="source SQLite path (default: $TENDERSCOUT_DB_PATH)",
    )
    parser.add_argument(
        "--database-url",
        default=os.environ.get("DATABASE_URL"),
        help="target DSN (default: $DATABASE_URL)",
    )
    parser.add_argument(
        "--skip-schema",
        action="store_true",
        help="do not apply supabase/migrations/001_init.sql first",
    )
    parser.add_argument(
        "--user-tables",
        action="store_true",
        help="also copy profiles/matches/saved/alerts/rfps/... "
        "(user_id values must be real auth UUIDs)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="report what would be copied without writing",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if not args.database_url:
        print(
            "error: DATABASE_URL is not set (target Postgres/Supabase DSN required)",
            file=sys.stderr,
        )
        return 2

    import psycopg
    from psycopg.rows import dict_row

    from storage import Storage

    sqlite_path = Path(args.sqlite)
    if not sqlite_path.exists():
        print(f"error: SQLite database not found: {sqlite_path}", file=sys.stderr)
        return 2

    # Opening through Storage applies the ALTER TABLE migrations, so
    # older databases expose the new columns to the copy below.
    storage = Storage(sqlite_path)
    tables = COLLECTOR_TABLES + (USER_TABLES if args.user_tables else [])

    try:
        with psycopg.connect(args.database_url, row_factory=dict_row) as conn:
            if not args.skip_schema and not args.dry_run:
                apply_schema(conn)

            total_inserted = total_skipped = 0
            for sqlite_table, pg_table, columns in tables:
                rows, usable = read_rows(storage.conn, sqlite_table, columns)
                if not rows:
                    print(f"  {sqlite_table:<26} skipped (absent or empty)")
                    continue
                if args.dry_run:
                    print(f"  {sqlite_table:<26} would copy {len(rows)} row(s)")
                    continue
                inserted, skipped = insert_rows(conn, pg_table, usable, rows)
                print(
                    f"  {sqlite_table:<26} -> {pg_table}: "
                    f"{inserted} inserted, {skipped} already present"
                )
                total_inserted += inserted
                total_skipped += skipped

            if args.dry_run:
                print("dry run: no rows written")
            else:
                print(
                    f"done: {total_inserted} row(s) inserted, "
                    f"{total_skipped} already present"
                )
    finally:
        storage.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
